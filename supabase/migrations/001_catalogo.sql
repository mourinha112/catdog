-- ---------------------------------------------------------------------
-- 1. Usuarios do painel administrativo
-- ---------------------------------------------------------------------
create table if not exists public.users (
  id         bigint generated by default as identity primary key,
  nome       text        not null,
  login      text        not null unique,
  senha_hash text        not null,
  role       text        not null default 'operador',   -- admin | operador
  ativo      boolean     not null default true,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2. Produtos do catalogo
--
-- Um produto pode ser vendido de tres formas, e o painel liga cada uma:
--   saco fechado  -> preco_saco_fechado + peso_saco_kg   (estoque em kg)
--   fracionado    -> preco_por_kg                        (estoque em kg)
--   por unidade   -> preco_unitario                      (estoque em un)
-- ---------------------------------------------------------------------
create table if not exists public.products (
  id                bigint generated by default as identity primary key,
  nome              text          not null,
  marca             text          default '',
  categoria         text          not null default 'racao',
  descricao         text,

  -- como aparece e como filtra no catalogo
  especie           text,          -- cao | gato | null (serve os dois)
  porte             text,          -- pequena | media | grande | null
  perfil            text,          -- filhote | adulto | castrado | senior | null
  foto_url          text,
  visivel_loja      boolean       not null default true,
  vende_fracionado  boolean       not null default true,

  -- precos
  peso_saco_kg      numeric(10,3) not null default 0,
  preco_saco_fechado numeric(10,2) not null default 0,
  preco_por_kg      numeric(10,4) not null default 0,
  preco_unitario    numeric(10,2) not null default 0,
  custo             numeric(10,2) not null default 0,

  -- estoque
  estoque_kg        numeric(10,3) not null default 0,
  estoque_unidade   integer       not null default 0,
  estoque_minimo    numeric(10,3) not null default 0,

  ativo             integer       not null default 1,
  created_at        timestamptz   not null default now(),
  updated_at        timestamptz   not null default now()
);

create index if not exists products_ativo_idx    on public.products (ativo);
create index if not exists products_especie_idx  on public.products (especie);
create index if not exists products_categoria_idx on public.products (categoria);

-- ---------------------------------------------------------------------
-- 3. Clientes (criados sozinhos no primeiro pedido, pelo WhatsApp)
-- ---------------------------------------------------------------------
create table if not exists public.clients (
  id             bigint generated by default as identity primary key,
  nome           text not null,
  whatsapp       text not null,
  endereco       text,
  referencia     text,
  observacao     text,
  ultimo_pedido  timestamptz,
  created_at     timestamptz not null default now()
);

create unique index if not exists clients_whatsapp_idx on public.clients (whatsapp);

-- ---------------------------------------------------------------------
-- 4. Pedidos
-- ---------------------------------------------------------------------
create table if not exists public.orders (
  id               bigint generated by default as identity primary key,
  client_id        bigint references public.clients(id) on delete set null,
  cliente_nome     text        not null,
  cliente_whatsapp text        not null,
  tipo_entrega     text        not null default 'entrega',  -- entrega | retirada
  endereco         text,
  referencia       text,
  janela           text,                                    -- "Hoje, 14h as 17h"
  observacao       text,
  subtotal         numeric(10,2) not null default 0,
  frete            numeric(10,2) not null default 0,
  total            numeric(10,2) not null default 0,
  status           text        not null default 'novo',
  -- novo | confirmado | separando | pronto | entregue | cancelado
  forma_pagamento  text,                                    -- dinheiro | pix | cartao
  assinatura       boolean     not null default false,
  frequencia       text,                                    -- semanal | quinzenal | mensal
  baixou_estoque   boolean     not null default false,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- quantidade_kg guarda a quantidade na unidade do tipo_venda:
--   'kg'      -> quilos
--   'saco'    -> numero de sacos fechados
--   'unidade' -> numero de unidades
create table if not exists public.order_items (
  id             bigint generated by default as identity primary key,
  order_id       bigint not null references public.orders(id) on delete cascade,
  product_id     bigint references public.products(id) on delete set null,
  descricao      text   not null,
  tipo_venda     text   not null default 'kg',
  quantidade_kg  numeric(10,3) not null default 0,
  preco_unitario numeric(10,4) not null default 0,
  subtotal       numeric(10,2) not null default 0
);

create index if not exists orders_status_idx     on public.orders (status);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_whatsapp_idx   on public.orders (cliente_whatsapp);
create index if not exists order_items_order_idx on public.order_items (order_id);
create index if not exists order_items_prod_idx  on public.order_items (product_id);

-- ---------------------------------------------------------------------
-- 5. Movimentacoes de estoque (historico de entrada e saida)
-- ---------------------------------------------------------------------
create table if not exists public.stock_movements (
  id            bigint generated by default as identity primary key,
  product_id    bigint references public.products(id) on delete cascade,
  tipo          text not null,                  -- entrada | saida | ajuste
  quantidade_kg numeric(10,3) not null default 0,
  quantidade_un integer not null default 0,
  motivo        text,
  order_id      bigint references public.orders(id) on delete set null,
  created_at    timestamptz not null default now()
);

create index if not exists stock_prod_idx on public.stock_movements (product_id);

