  for insert to anon, authenticated with check (bucket_id = 'produtos');
create policy produtos_troca on storage.objects
  for update to anon, authenticated using (bucket_id = 'produtos') with check (bucket_id = 'produtos');
create policy produtos_remocao on storage.objects
  for delete to anon, authenticated using (bucket_id = 'produtos');

-- ---------------------------------------------------------------------
-- 8. Acesso as tabelas
--
-- A chave anon (publica, que fica no navegador) precisa ler o catalogo e
-- gravar pedido. O resto passa pela API, que roda no servidor.
--
-- COMO FECHAR DE VERDADE (recomendado antes de crescer): coloque a
-- SUPABASE_SERVICE_ROLE_KEY nas variaveis da Vercel. A API ja usa ela
-- quando existe, e ai voce pode apagar as policies de leitura de orders,
-- clients e users, deixando o anon so com o catalogo e o INSERT de pedido.
-- ---------------------------------------------------------------------
alter table public.products        enable row level security;
alter table public.orders          enable row level security;
alter table public.order_items     enable row level security;
alter table public.clients         enable row level security;
alter table public.settings        enable row level security;
alter table public.users           enable row level security;
alter table public.stock_movements enable row level security;

do $$
declare t text;
begin
  foreach t in array array['products','orders','order_items','clients','settings','users','stock_movements']
  loop
    execute format('drop policy if exists %I_tudo on public.%I', t, t);
    execute format(
      'create policy %I_tudo on public.%I for all to anon, authenticated using (true) with check (true)',
      t, t);
  end loop;
end $$;

